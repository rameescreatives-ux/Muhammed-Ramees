  window.SHADOWX.chat = Object.assign({}, window.SHADOWX.chat, {

    autoOpenAfter: 20000,

    greeting: 'أهلًا — أنا رميس، مؤسس ShadowX Studios. أربعة أسئلة سريعة وأرسل لك عرض سعر حقيقي، عادة خلال ساعات قليلة.',

    /* نصوص النهاية والأزرار */
    text: {
      sending:  'ممتاز — أرسل التفاصيل إلى رميس الآن.',
      done:     'تم. سيصلك رد قريبًا، عادة خلال ساعات قليلة. سأفتح واتساب الآن لتضيف أي شيء آخر — مرجع بصري، موعد نهائي، أو صورة لما لديك حاليًا.',
      openWa:   'افتح واتساب',
      openMail: 'أرسل بريدًا بدلًا من ذلك',
      fallback: 'أهلًا — أربعة أسئلة سريعة وأرسل لك عرض سعر.'
    },

    /* مسار المحادثة بالكامل — عدّله كما تشاء */
    script: [
      {
        key: 'service',
        ask: 'ما الذي تحتاج تصميمه؟',
        options: [
          'شعار وهوية بصرية',
          'دليل علامة تجارية',
          'تصميم تغليف',
          'بروفايل شركة',
          'تصميم وبرمجة موقع',
          'إعادة تصميم الهوية',
          'لم أحدّد بعد'
        ]
      },
      {
        key: 'budget',
        ask: 'أي باقة أقرب لما تحتاجه؟ يمكنك تغييرها لاحقًا — هذا فقط ليعرف رميس ما يسعّره لك.',
        options: [
          'الانطلاق — 1,999 درهم',
          'الهوية — 2,999 درهم',
          'المتكاملة — 4,999 درهم',
          'نطاق أكبر / مخصّص',
          'ما زلت أفكر'
        ]
      },
      {
        key: 'timeline',
        ask: 'متى تحتاجه جاهزًا؟',
        options: ['في أقرب وقت', 'خلال شهر', 'من شهر إلى ثلاثة', 'أستكشف فقط']
      },
      {
        key: 'name',
        ask: 'تمام. بماذا أناديك؟',
        input: true,
        placeholder: 'اسمك',
        validate: function (v) {
          return v.trim().length >= 2 || 'الاسم الأول يكفي.';
        }
      },
      {
        key: 'contact',
        ask: function (lead) {
          return 'شكرًا ' + lead.name.split(' ')[0] + '. سؤال أخير — رقم واتساب أو بريدك الإلكتروني، لنرسل لك عرض السعر.';
        },
        input: true,
        placeholder: '+971 50 000 0000 أو you@company.com',
        validate: function (v) {
          var s = v.trim();
          var okEmail = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(s);
          var okPhone = /^[+\d][\d\s()-]{6,}$/.test(s);
          return (okEmail || okPhone) || 'يبدو أن هناك خطأ — رقم هاتف أو بريد إلكتروني، أيهما تفضّل.';
        }
      }
    ]
  });
